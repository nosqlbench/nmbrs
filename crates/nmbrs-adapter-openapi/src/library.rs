//! Render an OpenAPI spec as a library of reusable http op templates.
//!
//! Each operation becomes one `op_templates:` entry: the literal http
//! request shape (`method`, `uri`, `content_type`, `body`) with a typed
//! `abstract:` interface naming the fields it `needs`. The library runs
//! nothing by itself. A concrete workload `extends:` it and instantiates
//! the operations it wants with `uses:`, qualifying each one's needs
//! with its own bindings or params:
//!
//! ```yaml
//! extends: petstore_ops
//! phases:
//!   read:
//!     cycles: 1000
//!     ops:
//!       fetch:
//!         uses: getPetById
//!         bindings: |
//!           petId := mod(hash(cycle), 1000)
//! ```
//!
//! What an operation needs is what the spec says a request must carry:
//! its path parameters, its required query parameters, and its request
//! body's required fields. Optional ones are listed in a comment beside
//! the template; a workload that wants them declares its own template.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use openapiv3::OpenAPI;

use crate::spec::{ApiOperation, FieldInfo, ParamInfo};

/// The default target when the spec names no server.
pub const DEFAULT_BASE_URL: &str = "http://localhost:8080";

/// Render `ops`, parsed from `api`, as an op-template library document.
///
/// `source` names the spec file in the header. `base_url` overrides the
/// spec's first server as the `base_url` param's default.
pub fn render_op_library(
    api: &OpenAPI,
    ops: &[ApiOperation],
    source: &str,
    base_url: Option<&str>,
) -> String {
    let base_url = base_url
        .map(str::to_string)
        .or_else(|| api.servers.first().map(|s| s.url.clone()))
        .unwrap_or_else(|| DEFAULT_BASE_URL.to_string());
    let mut out = String::new();
    let title = &api.info.title;
    let version = &api.info.version;
    let _ = writeln!(out, "# {title} {version} — http op templates");
    let _ = writeln!(out, "#");
    let _ = writeln!(
        out,
        "# Generated by `openapi-ops` from {source}. Each operation below is a"
    );
    let _ = writeln!(
        out,
        "# reusable http request with the fields it needs declared under"
    );
    let _ = writeln!(
        out,
        "# `abstract.needs`. A workload `extends:` this file and instantiates an"
    );
    let _ = writeln!(
        out,
        "# operation with `uses: <operationId>`, supplying every need with a binding"
    );
    let _ = writeln!(
        out,
        "# (the op's, or its phase's, workload's, or scenario's) or a declared param:"
    );
    let _ = writeln!(out, "#");
    let _ = writeln!(out, "#   extends: ./<this file>");
    let _ = writeln!(out, "#   phases:");
    let _ = writeln!(out, "#     main:");
    let _ = writeln!(out, "#       cycles: 1000");
    let _ = writeln!(out, "#       ops:");
    let _ = writeln!(out, "#         my_op:");
    let _ = writeln!(out, "#           uses: <operationId>");
    let _ = writeln!(out, "#           bindings: |");
    let _ = writeln!(out, "#             <need> := <expression>");
    let _ = writeln!(out, "#");
    let _ = writeln!(
        out,
        "# The request shape is fixed by the template; the workload qualifies it."
    );
    let _ = writeln!(
        out,
        "# These are http requests: run the workload with `adapter=http`, and"
    );
    let _ = writeln!(
        out,
        "# `base_url=` to point it at a service other than the default below."
    );
    let _ = writeln!(
        out,
        "# Regenerate rather than edit: changes belong in the spec."
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "description: {}",
        yaml_str(&format!("{title} {version} http op templates"))
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "params:");
    let _ = writeln!(out, "  base_url: {}", yaml_str(&base_url));
    let _ = writeln!(out);
    let _ = writeln!(out, "op_templates:");

    let mut sorted: Vec<&ApiOperation> = ops.iter().collect();
    sorted.sort_by(|a, b| a.operation_id.cmp(&b.operation_id));
    for (i, op) in sorted.iter().enumerate() {
        if i > 0 {
            out.push('\n');
        }
        render_template(&mut out, op);
    }
    out
}

/// One operation's template, indented under `op_templates:`.
fn render_template(out: &mut String, op: &ApiOperation) {
    let needs = needs_of(op);
    let optional = optional_of(op);

    let _ = writeln!(out, "  # {} {}", op.method, op.path);
    if !optional.is_empty() {
        let list: Vec<String> = optional
            .iter()
            .map(|(name, typ)| format!("{name} ({typ})"))
            .collect();
        let _ = writeln!(out, "  # optional, not templated: {}", list.join(", "));
    }
    let _ = writeln!(out, "  {}:", yaml_key(&op.operation_id));
    if !op.summary.is_empty() {
        let _ = writeln!(out, "    description: {}", yaml_str(op.summary.trim()));
    }
    if !needs.is_empty() {
        let _ = writeln!(out, "    abstract:");
        let _ = writeln!(out, "      needs:");
        for (wire, typ) in &needs {
            let _ = writeln!(out, "        {wire}: {typ}");
        }
    }
    let _ = writeln!(out, "    method: {}", op.method);
    let _ = writeln!(out, "    uri: {}", yaml_str(&uri_of(op)));
    if let Some(body) = &op.request_body {
        let required: Vec<&FieldInfo> = body.fields.iter().filter(|f| f.required).collect();
        let _ = writeln!(out, "    content_type: {}", yaml_str(&body.content_type));
        let _ = writeln!(out, "    body: {}", yaml_str(&body_template(&required)));
    }
    if !op.tags.is_empty() {
        let _ = writeln!(out, "    tags:");
        let _ = writeln!(out, "      api_tag: {}", yaml_str(&op.tags.join(",")));
    }
}

/// The wires an operation needs, name → polydat type: its path
/// parameters, its required query parameters, and its body's required
/// fields.
fn needs_of(op: &ApiOperation) -> BTreeMap<String, &'static str> {
    let mut needs = BTreeMap::new();
    for p in op
        .path_params
        .iter()
        .chain(op.query_params.iter().filter(|p| p.required))
    {
        needs.insert(wire_name(&p.name), polydat_type(&p.schema_type));
    }
    if let Some(body) = &op.request_body {
        for f in body.fields.iter().filter(|f| f.required) {
            needs.insert(wire_name(&f.name), polydat_type(&f.schema_type));
        }
    }
    needs
}

/// The optional query parameters and body fields, name → polydat type.
fn optional_of(op: &ApiOperation) -> Vec<(String, &'static str)> {
    let params = op
        .query_params
        .iter()
        .filter(|p| !p.required)
        .map(|p: &ParamInfo| (p.name.clone(), polydat_type(&p.schema_type)));
    let fields = op
        .request_body
        .iter()
        .flat_map(|b| b.fields.iter().filter(|f| !f.required))
        .map(|f| (f.name.clone(), polydat_type(&f.schema_type)));
    params.chain(fields).collect()
}

/// `{base_url}` + the path with each `{param}` placeholder spelled as
/// its wire name, + the required query parameters.
fn uri_of(op: &ApiOperation) -> String {
    let mut path = op.path.clone();
    for p in &op.path_params {
        path = path.replace(
            &format!("{{{}}}", p.name),
            &format!("{{{}}}", wire_name(&p.name)),
        );
    }
    let query: Vec<String> = op
        .query_params
        .iter()
        .filter(|p| p.required)
        .map(|p| format!("{}={{{}}}", p.name, wire_name(&p.name)))
        .collect();
    if query.is_empty() {
        format!("{{base_url}}{path}")
    } else {
        format!("{{base_url}}{path}?{}", query.join("&"))
    }
}

/// A JSON body carrying `fields`, nested as their dotted names say, each
/// value a `{wire}` placeholder: bare for a number or boolean, quoted for
/// a string.
fn body_template(fields: &[&FieldInfo]) -> String {
    #[derive(Default)]
    struct Node {
        leaf: Option<String>,
        children: BTreeMap<String, Node>,
    }
    let mut root = Node::default();
    for f in fields {
        let mut node = &mut root;
        for part in f.name.split('.') {
            node = node.children.entry(part.to_string()).or_default();
        }
        let wire = wire_name(&f.name);
        node.leaf = Some(match f.schema_type.as_str() {
            "integer" | "number" | "boolean" => format!("{{{wire}}}"),
            _ => format!("\"{{{wire}}}\""),
        });
    }
    fn render(node: &Node) -> String {
        if let Some(leaf) = &node.leaf {
            return leaf.clone();
        }
        let members: Vec<String> = node
            .children
            .iter()
            .map(|(k, v)| format!("\"{k}\": {}", render(v)))
            .collect();
        format!("{{{}}}", members.join(", "))
    }
    render(&root)
}

/// A spec name as a wire name: a dotted body path joins with `_`, and
/// any other character a polydat identifier cannot carry becomes `_`.
pub fn wire_name(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

/// The polydat type a spec type is supplied as.
fn polydat_type(schema_type: &str) -> &'static str {
    match schema_type {
        "integer" => "u64",
        "number" => "f64",
        "boolean" => "bool",
        _ => "String",
    }
}

/// `s` as a double-quoted YAML scalar.
fn yaml_str(s: &str) -> String {
    serde_json::to_string(s).expect("a string serializes")
}

/// `s` as a YAML mapping key: bare when it is a plain identifier.
fn yaml_key(s: &str) -> String {
    if !s.is_empty() && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
        s.to_string()
    } else {
        yaml_str(s)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const SPEC: &str = r#"
openapi: 3.0.0
info: { title: Petstore, version: "1.0" }
servers:
  - url: http://pets.example:8080/v1
paths:
  /pets/{pet-id}:
    get:
      operationId: getPetById
      summary: Find a pet
      parameters:
        - { name: pet-id, in: path, required: true, schema: { type: integer } }
        - { name: verbose, in: query, required: false, schema: { type: boolean } }
      responses: { "200": { description: ok } }
  /pets:
    post:
      operationId: addPet
      requestBody:
        content:
          application/json:
            schema:
              type: object
              required: [name, owner]
              properties:
                name: { type: string }
                age: { type: integer }
                owner:
                  type: object
                  required: [id]
                  properties:
                    id: { type: integer }
      responses: { "201": { description: created } }
"#;

    fn library() -> String {
        let (api, ops) = crate::parse_spec(SPEC).expect("spec parses");
        render_op_library(&api, &ops, "petstore.yaml", None)
    }

    #[test]
    fn each_operation_is_a_template_with_its_typed_needs() {
        let lib = library();
        let doc: serde_json::Value = serde_yaml::from_str(&lib).expect("library is YAML");
        let get = &doc["op_templates"]["getPetById"];
        assert_eq!(get["method"], "GET");
        assert_eq!(get["uri"], "{base_url}/pets/{pet_id}");
        assert_eq!(get["abstract"]["needs"]["pet_id"], "u64");
        assert!(
            get["abstract"]["needs"].get("verbose").is_none(),
            "optional query stays out"
        );
        assert_eq!(doc["params"]["base_url"], "http://pets.example:8080/v1");
    }

    #[test]
    fn a_body_nests_its_required_fields() {
        let lib = library();
        let doc: serde_json::Value = serde_yaml::from_str(&lib).expect("library is YAML");
        let add = &doc["op_templates"]["addPet"];
        assert_eq!(
            add["body"],
            r#"{"name": "{name}", "owner": {"id": {owner_id}}}"#
        );
        assert_eq!(add["abstract"]["needs"]["owner_id"], "u64");
        assert!(lib.contains("optional, not templated: age (u64)"), "{lib}");
    }
}
